/**
 * Generate year options (past 5 years to next 2 years)
 */
export function getYearOptions() {
  const currentYear = new Date().getFullYear();
  const years = [];
  for (let y = currentYear - 3; y <= currentYear + 2; y++) {
    years.push(y);
  }
  return years;
}
